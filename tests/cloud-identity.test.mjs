test('resolveAuthAction: chỉ tạo tài khoản khi được cho phép rõ ràng', () => {
    // Chưa có lỗi -> đăng nhập bình thường.
    assert.equal(resolveAuthAction(null), 'signin');
    assert.equal(resolveAuthAction(undefined), 'signin');

    // 4 mã "không tìm thấy cặp email/mật khẩu": mặc định FAIL, không auto-create.
    for (const code of [
        'auth/user-not-found',
        'auth/invalid-credential',
        'auth/invalid-login-credentials',
        'auth/wrong-password'
    ]) {
        assert.equal(resolveAuthAction(code), 'fail', `${code} không được tự tạo tài khoản`);
        assert.equal(resolveAuthAction(code, { allowCreate: true }), 'create', `${code} chỉ tạo khi được phép`);
    }

    // Lỗi mạng / bị chặn / sai định dạng: luôn FAIL dù có cờ cho phép.
    for (const code of [
        'auth/network-request-failed',
        'auth/too-many-requests',
        'auth/user-disabled',
        'auth/invalid-email'
    ]) {
        assert.equal(resolveAuthAction(code, { allowCreate: true }), 'fail', `${code} không bao giờ được tạo tài khoản`);
    }

    // Mã lỗi rỗng/không phải chuỗi: không đoán, coi là thất bại.
    assert.equal(resolveAuthAction(''), 'fail');
    assert.equal(resolveAuthAction(42), 'fail');
});

test('pullWatermarkKey: watermark pull tách riêng theo uid', () => {
    assert.equal(pullWatermarkKey('uidA'), 'lastPullTime:uidA');
    assert.equal(pullWatermarkKey('uidB'), 'lastPullTime:uidB');
    assert.notEqual(pullWatermarkKey('uidA'), pullWatermarkKey('uidB'));
    assert.ok(pullWatermarkKey('uidA').startsWith('lastPullTime:'));
    // Không có uid -> rơi về khoá cũ (dùng cho fallback/migrate một lần).
    assert.equal(pullWatermarkKey(''), LEGACY_WATERMARK_KEY);
    assert.equal(pullWatermarkKey(null), LEGACY_WATERMARK_KEY);
    assert.equal(pullWatermarkKey(undefined), LEGACY_WATERMARK_KEY);
});

test('ensureCloudAuth: nhập sai mã không tạo tài khoản; chỉ tạo khi createIfMissing=true', async () => {
    const ls = memoryLocalStorage();
    try {
        const key = 'ABCDEFGH23456789';
        ls.storage.setItem(SYNC_KEY_STORAGE, key);
        const driver = authDriver({
            signInError: authError('auth/invalid-credential'),
            createdUser: { uid: 'uid-created', email: emailFor(key) }
        });

        const user = await ensureCloudAuth({ authDriver: driver });
        assert.equal(user, null);
        assert.equal(driver.calls.create, 0, 'mặc định không được tạo tài khoản');
        assert.equal(getCurrentUserId(), null);
        assert.equal(getLastCloudAuthFailure()?.code, 'auth/invalid-credential');

        const created = await ensureCloudAuth({ authDriver: driver, createIfMissing: true });
        assert.equal(driver.calls.create, 1);
        assert.equal(created.uid, 'uid-created');
        assert.equal(getCurrentUserId(), 'uid-created');
    } finally {
        ls.restore();
    }
});

test('applySyncKey thất bại: khôi phục mã cũ, uid cũ và watermark cũ', async () => {
    const ls = memoryLocalStorage();
    try {
        await ensureDB();
        const oldKey = 'ABCDEFGH23456789';
        const newKey = 'ZZZZZZZZZZZZZZZZZZZZ';
        ls.storage.setItem(SYNC_KEY_STORAGE, oldKey);

        // Đang đăng nhập không gian cũ.
        const oldUser = { uid: 'uid-old', email: emailFor(oldKey) };
        await ensureCloudAuth({ authDriver: authDriver({ user: oldUser }) });
        assert.equal(getCurrentUserId(), 'uid-old');

        await saveSettingToDB(LEGACY_WATERMARK_KEY, 4242);
        await saveSettingToDB(pullWatermarkKey('uid-old'), 9999);

        const failing = authDriver({ signInError: authError('auth/invalid-credential') });
        await assert.rejects(
            () => applySyncKey(newKey, { authDriver: failing }),
            error => error.code === SYNC_KEY_INVALID_CODE
                && /Mã không đúng hoặc không tồn tại/.test(error.message)
        );

        assert.equal(failing.calls.create, 0, 'không được tự tạo không gian rỗng');
        assert.equal(ls.storage.getItem(SYNC_KEY_STORAGE), oldKey, 'mã cũ được giữ nguyên');
        assert.equal(await getSettingFromDB(LEGACY_WATERMARK_KEY), 4242, 'watermark dùng chung cũ được khôi phục');
        assert.equal(await getSettingFromDB(pullWatermarkKey('uid-old')), 9999, 'watermark theo uid cũ được khôi phục');
        assert.equal(getCurrentUserId(), 'uid-old', 'uid cũ được khôi phục');
    } finally {
        ls.restore();
    }
});

test('applySyncKey createIfMissing=true: tạo không gian mới nhưng giữ tiến độ không gian cũ', async () => {
    const ls = memoryLocalStorage();
    try {
        await ensureDB();
        const oldKey = 'P2YV9NNSCHX98B4MB895';
        const newKey = 'MMMMNNNN22223333AAAA';
        ls.storage.setItem(SYNC_KEY_STORAGE, oldKey);

        const oldUser = { uid: 'uid-old-2', email: emailFor(oldKey) };
        await ensureCloudAuth({ authDriver: authDriver({ user: oldUser }) });
        assert.equal(getCurrentUserId(), 'uid-old-2');
        await saveSettingToDB(LEGACY_WATERMARK_KEY, 555);

        const newUser = { uid: 'uid-new-2', email: emailFor(newKey) };
        const driver = authDriver({
            signInError: authError('auth/user-not-found'),
            createdUser: newUser
        });
        const user = await applySyncKey(newKey, { createIfMissing: true, authDriver: driver });

        assert.equal(driver.calls.create, 1);
        assert.equal(user.uid, 'uid-new-2');
        assert.equal(getCurrentUserId(), 'uid-new-2');
        assert.equal(ls.storage.getItem(SYNC_KEY_STORAGE), newKey);
        assert.equal(await getSettingFromDB(pullWatermarkKey('uid-old-2')), 555, 'cursor không gian cũ được migrate sang khoá theo uid');
        assert.equal(await getSettingFromDB(LEGACY_WATERMARK_KEY), 0, 'watermark dùng chung bị vô hiệu hoá');
        assert.equal(await getSettingFromDB(pullWatermarkKey('uid-new-2')), undefined, 'không gian mới bắt đầu từ cursor rỗng');
    } finally {
        ls.restore();
    }
});

